/**
 * npm run content:build — src/content/**\/*.md → src/content/generated/*.json + index.ts (specs §1.3.5).
 * File names: legal/privacy.en.md, legal/terms.bn.md, en/learn.md, bn/dengue.md … (roadmap §5.4).
 * The generated folder is never edited by hand; content ships with EAS Update.
 */
import { mkdirSync, readdirSync, readFileSync, rmSync, statSync, writeFileSync } from 'node:fs';
import { dirname, join, relative, sep } from 'node:path';

import { LEGAL_IDS, type ContentDoc } from '../src/lib/content';
import { defaultSettings } from '../convex/rules/settings';
import { ContentError, legalProblems, markdownToDoc } from './lib/content';

const contentDir = join(process.cwd(), 'src', 'content');
const outDir = join(contentDir, 'generated');

function markdownFiles(dir: string): string[] {
  const out: string[] = [];
  for (const name of readdirSync(dir)) {
    const full = join(dir, name);
    if (full === outDir) continue;
    if (statSync(full).isDirectory()) out.push(...markdownFiles(full));
    else if (name.endsWith('.md') && name !== 'README.md') out.push(full);
  }
  return out.sort();
}

mkdirSync(contentDir, { recursive: true });
rmSync(outDir, { recursive: true, force: true });
mkdirSync(outDir, { recursive: true });

const ids: string[] = [];
const docs: Record<string, ContentDoc> = {};
let failed = false;
for (const file of markdownFiles(contentDir)) {
  const id = relative(contentDir, file).split(sep).join('/').replace(/\.md$/, '');
  try {
    const doc = markdownToDoc(readFileSync(file, 'utf8'), id);
    const target = join(outDir, `${id}.json`);
    mkdirSync(dirname(target), { recursive: true });
    writeFileSync(target, `${JSON.stringify(doc)}\n`);
    ids.push(id);
    docs[id] = doc;
  } catch (error) {
    failed = true;
    console.error(error instanceof ContentError ? error.message : error);
  }
}

// The legal version must equal the consentVersion that seed-settings writes (settings X08). A broken legal set is
// left out of the build entirely, so the app never shows a partial notice (the consent flow stays hidden).
const legal = legalProblems(docs, defaultSettings().consentVersion);
for (const problem of legal) console.error(problem);
if (legal.length > 0) {
  failed = true;
  for (const id of LEGAL_IDS) {
    const at = ids.indexOf(id);
    if (at !== -1) ids.splice(at, 1);
  }
}

const index = [
  '// Generated by scripts/build-content.ts — do not edit.',
  "import type { ContentDoc } from '@/lib/content';",
  '',
  'export const content: Record<string, ContentDoc> = {',
  ...ids.map((id) => `  ${JSON.stringify(id)}: require(${JSON.stringify(`./${id}.json`)}) as ContentDoc,`),
  '};',
  '',
].join('\n');
writeFileSync(join(outDir, 'index.ts'), index);

console.log(`Built ${ids.length} content page(s)${ids.length ? `: ${ids.join(', ')}` : ''}.`);
if (failed) process.exit(1);
